#!/usr/bin/env python3
"""Write every E2 base config: one per (engine, arm), each the E1' LinUCB-shared config of that
engine plus the arm's overrides plus E2's injected failure profile (`make_e2_profile.py`).

The two engine bases (`config_{pbft,snow}_linucb_shared.yml`) differ only in `consensus.protocol`,
so within an engine every arm differs from LinUCB-shared ONLY in the keys listed in ARMS, and the
same arm differs between engines only in the protocol. Regenerate rather than edit:

  python campaigns/make_e2_configs.py            # writes campaigns/e2/config_e2_<engine>_<arm>.yml

Arms (the guard is `mab.load_slack: 9` from the base, on for every bandit arm; `random` has no
bandit and so no guard):
  linucb-shared     the base: LinUCB, one ridge model for all groups, discount 0.995
  linucb-pergroup   mab.linucb.model: disjoint (one model per group)
  lints             mab.algorithm: lin_ts (shared model)
  eps               mab.algorithm: epsilon_greedy
  ucb1              mab.algorithm: ucb1
  random            mab.enabled: false (the no-bandit path picks top_k groups at random)
  linucb-noguard    linucb-shared with mab.load_slack: 0 — the guard ablation
E2a (failure flip at FLIP_AFTER_S of each agent's own failure clock):
  flip-linucb-d100  LinUCB-shared, discount 1.0 (no forgetting)
  flip-linucb-d098  LinUCB-shared, discount 0.98
  flip-eps-s0       epsilon-greedy, step_size null (lifetime average: no forgetting)
  flip-eps-s002     epsilon-greedy, step_size 0.02 (recency-weighted, the analogue of 0.98)
E2b (group outage; the outage itself is the campaign companion):
  linucb-nodecay    LinUCB-shared with context.timeout_decay_s 1e9: the per-group timeout signal
                    never fades, so an outage's timeouts stay in the features (the "decayed
                    timeout fix off" arm). Liveness gating has no off switch and is on in every arm.
"""
import copy
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))

from make_e2_profile import apply_profile, write_config  # noqa: E402
from swarm.utils.yaml_strict import safe_load as strict_load  # noqa: E402

ENGINES = {"pbft": "config_pbft_linucb_shared.yml", "snow": "config_snow_linucb_shared.yml"}
#: Seconds of each agent's failure clock (started at agent init, ~2 min before jobs are
#: distributed) before E2a's flip: ~300 s into the 600 s of Poisson-3/s arrivals.
FLIP_AFTER_S = 420.0

ARMS = {
    "linucb-shared": {},
    "linucb-pergroup": {"mab.linucb.model": "disjoint"},
    "lints": {"mab.algorithm": "lin_ts"},
    "eps": {"mab.algorithm": "epsilon_greedy"},
    "ucb1": {"mab.algorithm": "ucb1"},
    "random": {"mab.enabled": False},
    "linucb-noguard": {"mab.load_slack": 0},
    "flip-linucb-d100": {"mab.linucb.discount": 1.0, "_flip": True},
    "flip-linucb-d098": {"mab.linucb.discount": 0.98, "_flip": True},
    "flip-eps-s0": {"mab.algorithm": "epsilon_greedy", "mab.step_size": None, "_flip": True},
    "flip-eps-s002": {"mab.algorithm": "epsilon_greedy", "mab.step_size": 0.02, "_flip": True},
    "linucb-nodecay": {"mab.context.timeout_decay_s": 1.0e9},
}


def _set(cfg: dict, dotted: str, value) -> None:
    *path, last = dotted.split(".")
    node = cfg
    for k in path:
        if k not in node:
            raise SystemExit(f"{dotted}: no key {k!r} in the base config")
        node = node[k]
    if last not in node:
        raise SystemExit(f"{dotted}: no key {last!r} in the base config (refusing to invent one)")
    node[last] = value


def build(engine: str, arm: str) -> dict:
    cfg = strict_load(open(os.path.join(HERE, ENGINES[engine])))
    assert cfg["consensus"]["protocol"] == engine, (engine, cfg["consensus"]["protocol"])
    over = dict(ARMS[arm])
    flip = over.pop("_flip", False)
    for k, v in over.items():
        _set(cfg, k, v)
    apply_profile(cfg, flip_after_s=FLIP_AFTER_S if flip else None)
    return cfg


def main() -> int:
    out_dir = os.path.join(HERE, "e2")
    os.makedirs(out_dir, exist_ok=True)
    for engine, base in ENGINES.items():
        for arm, over in ARMS.items():
            cfg = build(engine, arm)
            shown = ", ".join(f"{k}={v}" for k, v in over.items() if not k.startswith("_")) or "none"
            header = (f"# Generated by campaigns/make_e2_configs.py: base {base}, arm {arm}, "
                      f"overrides: {shown}"
                      f"{f'; failure flip after {FLIP_AFTER_S:.0f} s' if over.get('_flip') else ''}.\n"
                      "# E2 failure profile from make_e2_profile.py (good 0.05, bad 0.8, mid 0.3). "
                      "Do not edit by hand; regenerate.\n")
            out = os.path.join(out_dir, f"config_e2_{engine}_{arm}.yml")
            write_config(cfg, out, header)
    print(f"wrote {len(ENGINES) * len(ARMS)} configs to {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
