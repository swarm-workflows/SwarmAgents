#!/usr/bin/env python3
"""Write an E2 base config: a base config plus the injected failure profile E2's oracle scores.

E2 runs Hier-90 with `--groups-per-coordinator 3`: three coordinators (88, 89, 90), each leading three
groups of leaves. A coordinator only ever chooses among ITS OWN three groups, so the profile's
contrast must sit inside each coordinator's set, or every choice is equivalent and routing
accuracy reads a meaningless 1.0 (CLAUDE.md, *Delegation regret*). Each coordinator gets one group
of each kind:

  ram-weak  fails ram_bound jobs at `--bad`, everything else at `--good`
  cpu-weak  fails cpu_bound jobs at `--bad`, everything else at `--good`
  mediocre  fails every job at `--mid`

No group is best for every job: a RAM-bound job's best group is the cpu-weak one and a CPU-bound
job's is the ram-weak one. On the replay-golden workload (64 % ram_bound, 34 % cpu_bound) a
context-blind policy can do no better than about 30 % failures (the cpu-weak or the mediocre group
for everything), while a contextual one can reach `--good`. The roles rotate across coordinators so
no group index means the same thing everywhere.

`--flip-after-s S` adds the E2a phase: after S seconds of each agent's own failure clock the
ram-weak and cpu-weak groups swap roles (the mediocre group is unchanged).

Group membership is generate_configs' partition for 90 agents at G=3, checked by regenerating with
the campaign's own flags (2026-10-15): groups 0-5 hold 10 leaves each (1-60), groups 6-8 hold 9
(61-87); coordinator 88 leads groups 0-2, 89 leads 3-5, 90 leads 6-8.

Usage:
  python campaigns/make_e2_profile.py campaigns/config_pbft_linucb_shared.yml campaigns/config_e2_pbft_linucb.yml
  python campaigns/make_e2_profile.py BASE OUT --flip-after-s 300      # E2a
"""
import argparse
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

from swarm.utils.yaml_strict import safe_load as strict_load  # noqa: E402

GROUPS = [list(range(1, 11)), list(range(11, 21)), list(range(21, 31)),
          list(range(31, 41)), list(range(41, 51)), list(range(51, 61)),
          list(range(61, 70)), list(range(70, 79)), list(range(79, 88))]
COORDINATORS = {88: [0, 1, 2], 89: [3, 4, 5], 90: [6, 7, 8]}
#: Role of each group, rotated across coordinators.
ROLES = {0: "ram-weak", 1: "cpu-weak", 2: "mediocre",
         3: "cpu-weak", 4: "mediocre", 5: "ram-weak",
         6: "mediocre", 7: "ram-weak", 8: "cpu-weak"}

JOB_TYPES = [f"{k}_{d}_{c}" for k in ("cpu_bound", "ram_bound", "disk_bound")
             for d in ("short", "medium", "long") for c in ("dtn_light", "dtn_heavy")]


def profile_for(role: str, good: float, bad: float, mid: float) -> dict:
    if role == "mediocre":
        return {"default": mid}
    weak = "ram_bound" if role == "ram-weak" else "cpu_bound"
    rates = {t: (bad if t.startswith(weak) else good) for t in JOB_TYPES}
    rates["default"] = good
    return rates


def per_agent(roles: dict, good: float, bad: float, mid: float) -> dict:
    out = {}
    for g, members in enumerate(GROUPS):
        rates = profile_for(roles[g], good, bad, mid)
        for aid in members:
            out[str(aid)] = dict(rates)
    return out


def flipped(roles: dict) -> dict:
    swap = {"ram-weak": "cpu-weak", "cpu-weak": "ram-weak", "mediocre": "mediocre"}
    return {g: swap[r] for g, r in roles.items()}


def check_contrast(roles: dict) -> None:
    """Every coordinator must hold one group of each role."""
    for coord, groups in COORDINATORS.items():
        have = sorted(roles[g] for g in groups)
        if have != ["cpu-weak", "mediocre", "ram-weak"]:
            raise SystemExit(f"coordinator {coord} has groups {have}: no within-coordinator contrast")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("base")
    ap.add_argument("out")
    ap.add_argument("--good", type=float, default=0.05)
    ap.add_argument("--bad", type=float, default=0.8)
    ap.add_argument("--mid", type=float, default=0.3)
    ap.add_argument("--flip-after-s", type=float, default=None)
    args = ap.parse_args()

    cfg = strict_load(open(args.base))
    if not cfg.get("mab", {}).get("enabled"):
        print(f"NOTE: mab.enabled is false in {args.base} — the `random` E2 arm; the profile still applies")
    sim = apply_profile(cfg, args.good, args.bad, args.mid, args.flip_after_s)
    header = (f"# Generated by campaigns/make_e2_profile.py from {os.path.basename(args.base)}: "
              f"good {args.good}, bad {args.bad}, mid {args.mid}"
              f"{f', flip after {args.flip_after_s:.0f} s' if args.flip_after_s is not None else ''}.\n"
              "# Do not edit by hand; regenerate.\n")
    write_config(cfg, args.out, header)
    print(f"wrote {args.out}: {len(sim['per_agent_failure_rates'])} leaf profiles"
          f"{', 1 flip phase' if 'phases' in sim else ''}")
    return 0


def apply_profile(cfg: dict, good: float = 0.05, bad: float = 0.8, mid: float = 0.3,
                  flip_after_s=None) -> dict:
    """Write E2's failure profile into `cfg['mab']['failure_simulation']` and return it."""
    check_contrast(ROLES)
    sim = {
        "enabled": True,
        "failure_probability": good,
        "per_agent_failure_rates": per_agent(ROLES, good, bad, mid),
        "per_job_type_failure_rates": {},
    }
    if flip_after_s is not None:
        sim["phases"] = [{"after_s": float(flip_after_s),
                          "per_agent_failure_rates": per_agent(flipped(ROLES), good, bad, mid)}]
    cfg.setdefault("mab", {})["failure_simulation"] = sim
    return sim


def write_config(cfg: dict, out: str, header: str) -> None:
    import yaml
    with open(out, "w") as f:
        f.write(header + yaml.safe_dump(cfg, sort_keys=False))


if __name__ == "__main__":
    sys.exit(main())
