#!/usr/bin/env python3
"""Generate the E5 arm configs (conference plan §4.2 E5). Regenerate; never edit the outputs.

    python3 campaigns/make_e5_configs.py

Each output is its base config with exactly ONE line changed, so an arm differs from the E1′
cell it is compared with in nothing but the ablated key:

  gossip off   gossip.enabled: true -> false                 (Hier-90, PBFT and Snow)
  peers        job_selection.coordinator_cost_matrix: self -> peers   (Hier-90 and Hier-270)

Bases are the E1′ analytic arm configs: PBFT Hier-90 campaigns/config_pbft.yml, PBFT Hier-270
campaigns/config_pbft_hier270.yml, Snow config_swarm_multi.yml (shipped). Refuses unless the line
to change appears exactly once.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GOSSIP = ("  enabled: true            # Peer load/utilization reaches Snow cost estimates via the",
          "  enabled: false           # E5 gossip-off arm (was true). Peer load/utilization reaches Snow cost estimates via the")
PEERS = ("  coordinator_cost_matrix: self",
         "  coordinator_cost_matrix: peers   # E5 peers arm (was self)")

ARMS = {
    "config_e5_pbft_gossipoff.yml": ("campaigns/config_pbft.yml", GOSSIP),
    "config_e5_snow_gossipoff.yml": ("config_swarm_multi.yml", GOSSIP),
    "config_e5_pbft_peers.yml": ("campaigns/config_pbft.yml", PEERS),
    "config_e5_pbft_hier270_peers.yml": ("campaigns/config_pbft_hier270.yml", PEERS),
    "config_e5_snow_peers.yml": ("config_swarm_multi.yml", PEERS),
}


def main():
    for out, (base, (old, new)) in ARMS.items():
        text = (ROOT / base).read_text()
        lines = text.split("\n")
        hits = [i for i, line in enumerate(lines) if line == old]
        if len(hits) != 1:
            raise SystemExit(f"{base}: expected exactly one line {old!r}, found {len(hits)}")
        lines[hits[0]] = new
        header = (f"# GENERATED by campaigns/make_e5_configs.py from {base}: one line changed\n"
                  f"# ({old.strip()!r} -> {new.split('#')[0].strip()!r}). Regenerate; never edit.\n")
        (ROOT / "campaigns" / out).write_text(header + "\n".join(lines))
        print(f"campaigns/{out}  <- {base}")


if __name__ == "__main__":
    main()
