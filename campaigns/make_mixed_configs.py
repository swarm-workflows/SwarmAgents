#!/usr/bin/env python3
"""Generate the real-execution configs for the mixed cells (T-6) and the §10 standalone pilot.
Regenerate; never edit the outputs.

    python3 campaigns/make_mixed_configs.py

Each output is an E1′ analytic arm config with exactly the six lines below changed, so a mixed
cell differs from the simulated cell it sits beside only in executing its real jobs:

  execution.mode            simulate -> real
  execution.work_dir        the NFS export -> a LOCAL directory (staging moves the files)
  execution.roots           {} -> {images: /export/images}   (each agent's local disk)
  execution.bundle          "" -> the merged job set on the export (code + root inputs)
  execution.staging.enabled false -> true
  execution.staging.store_host "" -> database   (staging_site.py: durable stage-out)

Simulated jobs carry no execution block and still sleep under `mode: real`.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MIXED = "/export/swarm-wf/mixed_1800_wf"       # 1800 simulated + cper-soilmoisture + eht-m87
PILOT = "/export/swarm-wf/wf_only"             # the real jobs alone (§10 standalone pilot)


def edits(bundle):
    return [
        ("    mode: simulate                # simulate | real",
         "    mode: real                    # simulate | real   (T-6: real jobs execute)"),
        ("    work_dir: /export/swarm-wf/work",
         "    work_dir: /var/tmp/swarm-wf/work   # LOCAL per agent: staging moves the files"),
        ("    roots: {}",
         "    roots: {images: /export/images}   # images on each agent's local disk"),
        ('    bundle: ""',
         f"    bundle: {bundle}"),
        ("    staging:\n      enabled: false",
         "    staging:\n      enabled: true"),
        ('      store_host: ""            # e.g. "database"; empty = no stage-out, not durable',
         '      store_host: database      # staging_site.py on the database node: durable stage-out'),
    ]


OUTPUTS = {
    "config_mixed_pbft.yml": ("campaigns/config_pbft.yml", MIXED),
    "config_mixed_snow.yml": ("config_swarm_multi.yml", MIXED),
    "config_wfpilot_snow.yml": ("config_swarm_multi.yml", PILOT),
}


def main():
    for out, (base, bundle) in OUTPUTS.items():
        text = (ROOT / base).read_text()
        for old, new in edits(bundle):
            n = text.count(old)
            if n != 1:
                raise SystemExit(f"{base}: expected exactly one {old!r}, found {n}")
            text = text.replace(old, new)
        header = (f"# GENERATED by campaigns/make_mixed_configs.py from {base} (bundle {bundle}).\n"
                  f"# Six execution lines changed; regenerate, never edit.\n")
        (ROOT / "campaigns" / out).write_text(header + text)
        print(f"campaigns/{out}  <- {base}")


if __name__ == "__main__":
    main()
